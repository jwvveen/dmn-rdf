"""Generate dmn-alignments.ttl: mappings to earlier DMN vocabularies.

    py scripts/generate_alignments.py

The sources are fetched at a fixed commit into sources/.cache/
(not committed). A mapping by IRI copies nothing from them.

* DMN-O (Nicholas Car, CSIRO), DMN 1.1, CC BY 4.0: same local name ->
  skos:closeMatch. Close and not exact: DMN-O describes DMN 1.1, and several
  classes changed meaning or members since (DecisionService, BKM).
* WHO SMART Guidelines KG, layer L2-DMN, Apache-2.0: six classes and
  invokedBy, by hand (their names differ), skos:closeMatch.
* CPRMV 0.4.0 (open-regels.nl), CC BY 4.0: rule management, not DMN; its
  decision model and decision are related to DMN's, not the same:
  skos:relatedMatch.

Only to terms that exist in the source files; the script checks that.
"""

from __future__ import annotations

import urllib.request
from pathlib import Path

import rdflib
from rdflib import OWL, RDF, URIRef

WORTEL = Path(__file__).resolve().parents[1]
MAP = WORTEL
CACHE = MAP / "sources" / ".cache"
NS = "https://w3id.org/dmn#"

DMNO = (
    "dmno.ttl",
    "https://raw.githubusercontent.com/nicholascar/dmn-ont/"
    "51803bd0c95094b10dd5c384b6d3c6dd37a8e120/dmn.ttl",
    "http://promsns.org/def/dmn#",
)
WHO = (
    "who-l2-dmn.ttl",
    "https://raw.githubusercontent.com/WorldHealthOrganization/smart-kg/"
    "90dc95c02fb2d5cde5fa4ce5a7e4e5ac844496de/ontology/l2-dmn/l2-dmn.ttl",
    "http://smart.who.int/kg/",
)
CPRMV = (
    "cprmv.ttl",
    "https://raw.githubusercontent.com/sgort/cprmv/"
    "a4e5dc9bd8374e6150183fa47049985e1a0fd712/rdf/cprmv.ttl",
    "https://standaarden.open-regels.nl/standards/cprmv/0.4.0#",
)

WHO_KAART = {
    "Definitions": "DMNFile",
    "Decision": "DMNDecision",
    "DecisionTable": "DMNDecisionTable",
    "InputClause": "DMNInputClause",
    "OutputClause": "DMNOutputClause",
    "DecisionRule": "DMNRule",
    "usingTask": "invokedBy",
}
CPRMV_KAART = {"Definitions": "DecisionModel", "Decision": "Decision"}


def _bron(naam: str, url: str) -> rdflib.Graph:
    pad = CACHE / naam
    if not pad.exists():
        CACHE.mkdir(parents=True, exist_ok=True)
        with urllib.request.urlopen(url, timeout=60) as r:  # noqa: S310 - vaste https-url
            pad.write_bytes(r.read())
    g = rdflib.Graph()
    g.parse(pad, format="turtle")
    return g


def _termen(g: rdflib.Graph, ns: str) -> set[str]:
    typen = (OWL.Class, rdflib.RDFS.Class, OWL.ObjectProperty, OWL.DatatypeProperty, RDF.Property)
    return {
        str(s)[len(ns) :]
        for t in typen
        for s in g.subjects(RDF.type, t)
        if isinstance(s, URIRef) and str(s).startswith(ns) and len(str(s)) > len(ns)
    }


def genereer() -> tuple[str, list[str]]:
    eigen = rdflib.Graph()
    eigen.parse(MAP / "dmn.ttl", format="turtle")
    onze = _termen(eigen, NS)
    uit = [
        f"@prefix dmn: <{NS}> .",
        "@prefix skos: <http://www.w3.org/2004/02/skos/core#> .",
        "@prefix dct: <http://purl.org/dc/terms/> .",
        "@prefix owl: <http://www.w3.org/2002/07/owl#> .",
        f"@prefix dmno: <{DMNO[2]}> .",
        f"@prefix sgkg: <{WHO[2]}> .",
        f"@prefix cprmv: <{CPRMV[2]}> .",
        "",
        "# GENERATED by scripts/generate_alignments.py. Only to terms that exist in the",
        "# source files (fetched at a fixed commit); no axioms or labels are copied from them.",
        "",
        f"<{NS.rstrip('#')}/alignments> a owl:Ontology ;",
        '    dct:title "DMN 1.6 in RDF: alignments to earlier DMN vocabularies"@en ;',
        "    dct:license <https://creativecommons.org/licenses/by/4.0/> ;",
        '    owl:versionInfo "0.1.0" .',
        "",
    ]
    telling = []
    hun = _termen(_bron(DMNO[0], DMNO[1]), DMNO[2])
    paren = sorted(onze & hun)
    uit.append("# DMN-O, DMN 1.1 (nicholascar/dmn-ont): same local name, skos:closeMatch")
    uit += [f"dmn:{t} skos:closeMatch dmno:{t} ." for t in paren]
    telling.append(f"DMN-O {len(paren)}")
    for (naam, url, ns), kaart, rel, kop, px in (
        (WHO, WHO_KAART, "skos:closeMatch", "WHO SMART Guidelines KG, layer L2-DMN", "sgkg"),
        (CPRMV, CPRMV_KAART, "skos:relatedMatch", "CPRMV 0.4.0 (open-regels.nl)", "cprmv"),
    ):
        hun = _termen(_bron(naam, url), ns)
        ontbreekt = [h for o, h in kaart.items() if h not in hun or o not in onze]
        if ontbreekt:
            raise SystemExit(f"{kop}: term niet gevonden: {ontbreekt}")
        uit += ["", f"# {kop}: {rel}"] + [
            f"dmn:{o} {rel} {px}:{h} ." for o, h in sorted(kaart.items())
        ]
        telling.append(f"{px} {len(kaart)}")
    return "\n".join(uit) + "\n", telling


def main() -> None:
    tekst, telling = genereer()
    (MAP / "dmn-alignments.ttl").write_text(tekst, encoding="utf-8", newline="\n")
    print("dmn-alignments.ttl:", ", ".join(telling))


if __name__ == "__main__":
    main()
