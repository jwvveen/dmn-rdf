"""Generate the DMN requirements matrix, the hit policies and the rule catalogue as RDF.

    py scripts/generate_matrix_ttl.py

Source: sources/dmn-rules.json, extracted from the DMN 1.6
specification (Table 2 in clause 6.2.3, clause 8.2.11 and the normative
sentences of clauses 6 to 10). Writes:

  dmn-matrix.ttl  the 25 cells of Table 2, each with what the
                               specification permits and what the schema
                               accepts; the seven hit policies and four
                               aggregations with their properties as data
  dmn-rules.ttl   the normative sentences as a catalogue, each
                               with the shape or check that tests it, or the
                               reason nothing does
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

WORTEL = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(WORTEL / "scripts"))
from generate_ontology_ttl import NS, lit, waarde_iri  # noqa: E402

MAP = WORTEL
SPEC = "https://www.omg.org/spec/DMN/1.6/PDF"
SH = "https://w3id.org/dmn/shapes#"

KOP = [
    f"@prefix dmn: <{NS}> .",
    "@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .",
    "@prefix owl: <http://www.w3.org/2002/07/owl#> .",
    "@prefix xsd: <http://www.w3.org/2001/XMLSchema#> .",
    "@prefix dct: <http://purl.org/dc/terms/> .",
    f"@prefix dmnsh: <{SH}> .",
    "",
]


def _bool(b: bool) -> str:
    return "true" if b else "false"


def _bron() -> dict:
    return json.loads((MAP / "sources" / "dmn-rules.json").read_text(encoding="utf-8"))


VOCAB = f"""# The matrix vocabulary. Not part of the OMG metamodel.
dmn:RequirementRule a owl:Class ;
    rdfs:label {lit("Requirement rule")}, {lit("Vereisteregel", "nl")} ;
    rdfs:comment {lit("One cell of Table 2 of DMN 1.6 (clause 6.2.3): may an element of the requiring type require an element of the required type, and with which kind of requirement? Also records what DMN16.xsd and DMN16.xmi accept, which differs in four cells.")} .
dmn:requiredType a owl:ObjectProperty ; rdfs:label {lit("required type")} ; rdfs:domain dmn:RequirementRule ;
    rdfs:comment {lit("Column From of Table 2: the element that is required.")} .
dmn:requiringType a owl:ObjectProperty ; rdfs:label {lit("requiring type")} ; rdfs:domain dmn:RequirementRule ;
    rdfs:comment {lit("Column To (Required by) of Table 2: the element that owns the requirement.")} .
dmn:requirementType a owl:ObjectProperty ; rdfs:label {lit("requirement type")} ; rdfs:domain dmn:RequirementRule .
dmn:permitted a owl:DatatypeProperty ; rdfs:label {lit("permitted")}, {lit("toegestaan", "nl")} ; rdfs:range xsd:boolean .
dmn:schemaAccepts a owl:ObjectProperty ; rdfs:label {lit("schema accepts")} ;
    rdfs:comment {lit("A requirement class that DMN16.xsd and DMN16.xmi structurally accept for this pair.")} .
dmn:schemaMismatch a owl:ObjectProperty ; rdfs:label {lit("schema mismatch")} ;
    rdfs:comment {lit("A requirement class that the schema accepts for this pair but the specification forbids.")} .
dmn:specCell a owl:DatatypeProperty ; rdfs:label {lit("specification cell")} .

# Hit policies and aggregations as data (clause 8.2.11).
dmn:letter a owl:DatatypeProperty ; rdfs:label {lit("letter")} ;
    rdfs:comment {lit("The hit policy indicator printed in the table.")} .
dmn:singleHit a owl:DatatypeProperty ; rdfs:label {lit("single hit")} ; rdfs:range xsd:boolean .
dmn:ruleOrderMatters a owl:DatatypeProperty ; rdfs:label {lit("rule order matters")} ; rdfs:range xsd:boolean .
dmn:overlapAllowed a owl:DatatypeProperty ; rdfs:label {lit("overlap allowed")} ; rdfs:range xsd:boolean .
dmn:needsOutputValues a owl:DatatypeProperty ; rdfs:label {lit("needs output values")} ; rdfs:range xsd:boolean .
dmn:compoundOutputAllowed a owl:DatatypeProperty ; rdfs:label {lit("compound output allowed")} ; rdfs:range xsd:boolean .
dmn:aggregationAllowed a owl:DatatypeProperty ; rdfs:label {lit("aggregation allowed")} ; rdfs:range xsd:boolean .
dmn:operator a owl:DatatypeProperty ; rdfs:label {lit("operator")} .
dmn:feelFunction a owl:DatatypeProperty ; rdfs:label {lit("FEEL function")} .
dmn:verbatim a owl:DatatypeProperty ; rdfs:label {lit("verbatim text")} .
dmn:clause a owl:DatatypeProperty ; rdfs:label {lit("clause")} .
dmn:page a owl:DatatypeProperty ; rdfs:label {lit("page")} .

"""


def matrix() -> str:
    d = _bron()
    req = d["requirements"]
    labels = {o["id"]: o["label"] for o in req["objects"]}
    uit = list(KOP) + [
        "# GENERATED by scripts/generate_matrix_ttl.py from sources/dmn-rules.json",
        "# (DMN 1.6, formal/25-12-02, Table 2 and clause 8.2.11). Do not edit by hand.",
        "",
        f"<{NS.rstrip('#')}/matrix> a owl:Ontology ;",
        f"    dct:title {lit('DMN 1.6 in RDF: requirements matrix and hit policies')} ;",
        f"    owl:imports <{NS.rstrip('#')}> ;",
        "    dct:license <https://creativecommons.org/licenses/by/4.0/> ;",
        '    owl:versionInfo "0.1.0" .',
        "",
        VOCAB,
    ]
    for r in req["rules"]:
        paren = [
            "a dmn:RequirementRule",
            f"dmn:requiredType dmn:{r['from']}",
            f"dmn:requiringType dmn:{r['to']}",
            f"dmn:permitted {_bool(r['allowed'])}",
            f"dmn:specCell {lit('DMN 1.6 Table 2 (6.2.3), from ' + labels[r['from']] + ' to ' + labels[r['to']])}",
            f'dmn:page "{r.get("page", req.get("page", ""))}"',
            f"dct:source <{SPEC}>",
        ]
        if r.get("requirement"):
            paren.append(f"dmn:requirementType dmn:{r['requirement']}")
        paren += [f"dmn:schemaAccepts dmn:{k}" for k in r.get("schemaAllows", [])]
        paren += [f"dmn:schemaMismatch dmn:{k}" for k in r.get("schemaMismatch", [])]
        if r.get("note"):
            paren.append(f"rdfs:comment {lit(r['note'])}")
        uit.append(f"dmn:req-{r['from']}-{r['to']} " + " ;\n    ".join(paren) + " .\n")
    for h in d["hitPolicies"]:
        paren = [
            f'dmn:letter "{h["letter"]}"',
            f"dmn:singleHit {_bool(h['single'])}",
            f"dmn:ruleOrderMatters {_bool(h['ruleOrderMatters'])}",
            f"dmn:overlapAllowed {_bool(h['overlapAllowed'])}",
            f"dmn:needsOutputValues {_bool(h['needsOutputValues'])}",
            f"dmn:compoundOutputAllowed {_bool(h['compoundOutputAllowed'])}",
            f"dmn:aggregationAllowed {_bool(h['id'] == 'COLLECT')}",
            f"dmn:verbatim {lit(h['definition'])}",
            f'dmn:clause "{h["section"]}"',
            f'dmn:page "{h["page"]}"',
            f"dct:source <{SPEC}>",
        ]
        if h.get("note"):
            paren.append(f"rdfs:comment {lit(h['note'])}")
        uit.append(f"{waarde_iri('HitPolicy', h['id'])} " + " ;\n    ".join(paren) + " .\n")
    for a in d["aggregators"]:
        paren = [
            f'dmn:operator "{a["operator"]}"',
            f'dmn:letter "{a["indicator"]}"',
            f'dmn:feelFunction "{a["feelFunction"]}"',
            f"dmn:verbatim {lit(a['definition'])}",
            f'dmn:clause "{a["section"]}"',
            f'dmn:page "{a["page"]}"',
            f"dct:source <{SPEC}>",
        ]
        uit.append(f"{waarde_iri('BuiltinAggregator', a['id'])} " + " ;\n    ".join(paren) + " .\n")
    return "\n".join(uit)


def regels(dekking: dict[int, str]) -> str:
    d = _bron()
    uit = list(KOP) + [
        "# GENERATED by scripts/generate_matrix_ttl.py: the normative sentences of DMN 1.6",
        "# that constrain models, each with the shape or check that tests it. Do not edit by",
        "# hand; the coverage is kept in scripts/coverage.py.",
        "",
        f"<{NS.rstrip('#')}/rules> a owl:Ontology ;",
        f"    dct:title {lit('DMN 1.6 in RDF: catalogue of normative statements')} ;",
        "    dct:license <https://creativecommons.org/licenses/by/4.0/> ;",
        '    owl:versionInfo "0.1.0" .',
        "",
        f"""dmn:NormativeStatement a owl:Class ;
    rdfs:label {lit("Normative statement")}, {lit("Normatieve uitspraak", "nl")} ;
    rdfs:comment {lit("A sentence from the DMN specification that constrains models, quoted verbatim with its clause and page.")} .
dmn:checkedBy a owl:ObjectProperty ; rdfs:label {lit("checked by")} ; rdfs:domain dmn:NormativeStatement .
dmn:notCheckedBecause a owl:DatatypeProperty ; rdfs:label {lit("not checked because")} .
dmn:strength a owl:DatatypeProperty ; rdfs:label {lit("strength")} ;
    rdfs:comment {lit("SHALL, SHOULD or MAY as written, or DEFINITION for a definition a check relies on.")} .
dmn:topic a owl:DatatypeProperty ; rdfs:label {lit("topic")} .
dmn:clause a owl:DatatypeProperty ; rdfs:label {lit("clause")} .
dmn:page a owl:DatatypeProperty ; rdfs:label {lit("page")} .
dmn:verbatim a owl:DatatypeProperty ; rdfs:label {lit("verbatim text")} .
""",
    ]
    for i, c in enumerate(d["constraints"], start=1):
        paren = [
            "a dmn:NormativeStatement",
            f"dmn:clause {lit(str(c['section']))}",
            f'dmn:page "{c["page"]}"',
            f'dmn:topic "{c["topic"]}"',
            f'dmn:strength "{c.get("strength", "SHALL")}"',
            f"dmn:verbatim {lit(c['text'])}",
            f"dct:source <{SPEC}>",
        ]
        if c.get("note"):
            paren.append(f"rdfs:comment {lit(c['note'])}")
        waarde = dekking.get(i, "")
        if waarde.startswith("dmnsh:"):
            paren += [f"dmn:checkedBy {s.strip()}" for s in waarde.split(",")]
        elif waarde:
            paren.append(f"dmn:notCheckedBecause {lit(waarde)}")
        uit.append(f"dmn:statement-{i:03d} " + " ;\n    ".join(paren) + " .\n")
    return "\n".join(uit)


def main() -> None:
    from coverage import DEKKING

    (MAP / "dmn-matrix.ttl").write_text(matrix(), encoding="utf-8", newline="\n")
    (MAP / "dmn-rules.ttl").write_text(regels(DEKKING), encoding="utf-8", newline="\n")
    n = len(_bron()["constraints"])
    gedekt = sum(1 for i in range(1, n + 1) if DEKKING.get(i, "").startswith("dmnsh:"))
    reden = sum(
        1 for i in range(1, n + 1) if DEKKING.get(i, "") and not DEKKING[i].startswith("dmnsh:")
    )
    print(
        f"matrix en regelcatalogus geschreven; {gedekt} van {n} uitspraken gecontroleerd, "
        f"{reden} met een reden waarom niet, {n - gedekt - reden} nog zonder"
    )


if __name__ == "__main__":
    main()
